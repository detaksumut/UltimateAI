// Helper functions for the banner UI
export function getHikmahById(id) {
  const cleanId = ((id - 1) % AL_HIKAM_WISDOMS.length) + 1;
  return AL_HIKAM_WISDOMS.find(h => h.id === cleanId) || AL_HIKAM_WISDOMS[0];
}

export function getRandomHikmah() {
  const randIdx = Math.floor(Math.random() * AL_HIKAM_WISDOMS.length);
  return AL_HIKAM_WISDOMS[randIdx];
}

export const TOTAL_HIKMAH = AL_HIKAM_WISDOMS.length;
export default AL_HIKAM_WISDOMS;
